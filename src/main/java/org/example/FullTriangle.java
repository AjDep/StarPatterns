package org.example;

public class FullTriangle {
    FullTriangle(){
        for(int i=0;i<=5;i++){
            for(int j=i;j<=5;j++){
                System.out.print(" ");
            }
            for(int j=0;j<=i;j++){
                System.out.print("0");
            }
            for(int j=0;j<=i;j++){
                System.out.print("0");
            }





            System.out.println();

        }
    }
}
